"use client";

import { useEffect, useRef, useState } from "react";

/**
 * Wrap any section in <Reveal> to have it fade + slide in once it scrolls
 * into the viewport, instead of animating on page load regardless of
 * scroll position. Uses IntersectionObserver so it's cheap and only fires
 * once per element (via the `visible` state never resetting to false).
 */
export default function Reveal({
  children,
  className = "",
}: {
  children: React.ReactNode;
  className?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const node = ref.current;
    if (!node) return;

    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true);
          observer.disconnect(); // only reveal once, no re-triggering on scroll up/down
        }
      },
      { threshold: 0.15 }
    );

    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`${className} transition-all duration-700 ease-out ${
        visible ? "opacity-100 translate-y-0" : "opacity-0 translate-y-6"
      }`}
    >
      {children}
    </div>
  );
}
